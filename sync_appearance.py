#!/usr/bin/env python3
"""Compile independent appearance profiles into native themes/layouts and mod helpers."""
import argparse
import copy
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
MODS = ('prodsovet', 'my-files', 'file-tab', 'find', 'session_fork')
# Optional per-profile drawing style. A profile without `style` draws exactly as
# the classic ProdAdvice code did; these constants are that classic look, not
# values borrowed from another profile.
CLASSIC_STYLE = {
    'radiusScale': 1,      # multiplier for every custom-mod corner radius
    'brandFont': None,     # brand title font; null keeps fonts.ui
    'labelFont': 'ui',     # section labels/status strip: "ui" or "mono"
    'brandChip': False,    # subtitle as an accent chip with inverse text
    'selectionBar': False, # 2 px accent bar at the left of selected rows
    'agency': False,       # agency-page decoration: dither, ticks, rails, sphere, glitch
    'agentAccents': None,  # {kind: {dark, light}} accent per agent kind; null uses the theme
}


def generated(profiles):
    # Herdr does not allow imports between mod directories. These identical files
    # are generated from one config; behavior modules remain shared by layouts.
    return '''// Generated by sync_appearance.py from appearance_profiles.json. Do not edit.
import { shared, settings } from "herdr";
export const allProfiles = ''' + json.dumps(profiles, ensure_ascii=False, indent=2) + ''';
// Earlier layout names (0.3 and a short-lived 0.4 draft), still recognized while an old install is around.
const FORMER = { "ProdAdvice": "PA-Light", "ProdAdvice2": "PA-Advanced", "ProdAdvice-Light": "PA-Light", "ProdAdvice-Advanced": "PA-Advanced" };
export function profileName() {
  const name = FORMER[shared("layout")] ?? shared("layout");
  return Object.prototype.hasOwnProperty.call(allProfiles, name) ? name : "PA-Light";
}
export function appearance(name = profileName()) {
  return allProfiles[FORMER[name] ?? name] ?? allProfiles["PA-Light"];
}
// The full layout: project tree, GitHub panel and the agency look.
export const advanced = () => profileName() === "PA-Advanced";
function value(group, key) {
  const result = key.split(".").reduce((node, part) => node?.[part], appearance()[group]);
  if (typeof result !== "number" || !Number.isFinite(result)) throw new Error(`Unknown appearance ${group}: ${key}`);
  return result;
}
export const fontSize = key => value("text", key);
export const metric = key => value("metrics", key);
const CLASSIC_STYLE = ''' + json.dumps(CLASSIC_STYLE) + ''';
export function style(key) {
  const own = appearance().style;
  if (!Object.prototype.hasOwnProperty.call(CLASSIC_STYLE, key)) throw new Error(`Unknown appearance style: ${key}`);
  return own && Object.prototype.hasOwnProperty.call(own, key) ? own[key] : CLASSIC_STYLE[key];
}
export const radius = n => n * style("radiusScale");
export const labelFont = () => (style("labelFont") === "mono" ? appearance().fonts.mono : null);
export const brandFont = () => style("brandFont") ?? appearance().fonts.ui;
// Interface language, shared by every mod: English unless "ru" is chosen.
export const lang = () => (shared("ui.lang") === "ru" ? "ru" : "en");
export const L = (en, ru) => (lang() === "ru" ? ru : en);
// The agent kind's own accent (claude, codex, gemini, hermes, other), or null.
export function agentAccent(kind) {
  const all = style("agentAccents");
  const own = all?.[kind] ?? all?.other;
  return own ? own[settings()?.dark === false ? "light" : "dark"] : null;
}
'''


def validate(config):
    if config.get('version') != 1:
        raise ValueError('Unsupported profile format')
    profiles = config['profiles']
    if set(profiles) != {'PA-Light', 'PA-Advanced'}:
        raise ValueError('Expected independent PA-Light and PA-Advanced profiles')
    for name, p in profiles.items():
        if not re.fullmatch(r'[A-Za-z0-9_-]+', name):  # Herdr refuses spaces in key sections
            raise ValueError('Unsafe layout name')
        for key in ('ui', 'terminal', 'mono', 'editor'):
            if not isinstance(p['fonts'][key], str) or not p['fonts'][key].strip():
                raise ValueError(f'{name}: missing font {key}')
        if not 8 <= p['fonts']['terminalSize'] <= 72:
            raise ValueError('Invalid terminal font size')
        for section in ('text', 'metrics'):
            for group in p[section].values():
                for n in group.values():
                    if not isinstance(n, (int, float)) or isinstance(n, bool) or not math.isfinite(n) or n <= 0:
                        raise ValueError(f'{name}: invalid {section} value')
        preview = Path(p['preview'])
        if preview.is_absolute() or '..' in preview.parts or preview.parts[0] != 'layouts':
            raise ValueError('Unsafe preview path')
        if not isinstance(p['agentTints'], bool):
            raise ValueError('agentTints must be a boolean')
        light = p.get('lightPalette')
        for key in ('lightTheme', 'darkThemeName'):
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]*', p[key]):
                raise ValueError(f'Unsafe theme name: {key}')
        own_style = p.get('style')
        if own_style is not None:
            if not isinstance(own_style, dict) or set(own_style) - set(CLASSIC_STYLE):
                raise ValueError(f'{name}: unknown style keys')
            scale = own_style.get('radiusScale', 1)
            if not isinstance(scale, (int, float)) or isinstance(scale, bool) or not 0 <= scale <= 2:
                raise ValueError(f'{name}: radiusScale must be 0..2')
            font = own_style.get('brandFont')
            if font is not None and (not isinstance(font, str) or not font.strip()):
                raise ValueError(f'{name}: invalid brandFont')
            if own_style.get('labelFont', 'ui') not in ('ui', 'mono'):
                raise ValueError(f'{name}: labelFont must be ui or mono')
            accents = own_style.get('agentAccents')
            if accents is not None:
                if not isinstance(accents, dict) or any(not isinstance(v, dict) or set(v) != {'dark', 'light'} for v in accents.values()):
                    raise ValueError(f'{name}: agentAccents must map kinds to dark/light colors')
                colors_ok = all(isinstance(c, str) and re.fullmatch(r'#[0-9a-fA-F]{6}', c) for v in accents.values() for c in v.values())
                if not colors_ok:
                    raise ValueError(f'{name}: agentAccents colors must be #rrggbb')
            for key in ('brandChip', 'selectionBar', 'agency'):
                if not isinstance(own_style.get(key, False), bool):
                    raise ValueError(f'{name}: {key} must be a boolean')
        colors = [*p['brandColors'].values(), *p['darkTheme']['ansi'], *p['darkTheme'].get('colors', {}).values()]
        colors += [p['darkTheme'][k] for k in ('background', 'foreground', 'selection', 'cursor') if k in p['darkTheme']]
        if light is not None:
            if len(light['ansi']) != 16:
                raise ValueError('Light palette needs 16 ANSI colors')
            colors += [light[k] for k in ('background', 'foreground', 'selection', 'cursor')]
            colors += [*light['ansi'], *light.get('colors', {}).values()]
        colors += [c for palette in p['agentPalettes'].values() for c in palette.values()]
        if any(not isinstance(c, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', c) for c in colors):
            raise ValueError(f'{name}: colors must be #rrggbb')
    # Each profile owns a complete schema. Missing values must not fall through
    # to the other profile and accidentally couple their appearances.
    def shape(obj):
        return {k: shape(v) for k, v in obj.items() if k not in ('lightPalette', 'style')} if isinstance(obj, dict) else None
    if shape(profiles['PA-Light']) != shape(profiles['PA-Advanced']):
        raise ValueError('Profiles must have the same complete schema')
    owned = set(profiles)
    for p in profiles.values():
        if p['darkThemeName'] in owned:
            raise ValueError('Theme names must be independent')
        owned.add(p['darkThemeName'])
        if p.get('lightPalette') is not None:
            if p['lightTheme'] in owned:
                raise ValueError('Theme names must be independent')
            owned.add(p['lightTheme'])
    return profiles


def plan(home, config_path=None):
    home = Path(home).resolve()
    profiles = validate(json.loads(Path(config_path or ROOT / 'appearance_profiles.json').read_text()))
    result = {}
    helper = generated(profiles)
    for mod in MODS:
        folder = home / 'mods' / mod
        if not folder.is_dir():
            raise ValueError(f'Missing mod directory: {mod}')
        result[folder / 'appearance.js'] = helper
    base = json.loads((home / 'layouts/PA-Light.json').read_text())
    for name, p in profiles.items():
        path = home / 'layouts' / (name + '.json')
        layout = json.loads(path.read_text()) if path.exists() else copy.deepcopy(base)
        layout.update(ui_font=p['fonts']['ui'], font=p['fonts']['terminal'], font_size=p['fonts']['terminalSize'],
                      theme={'light': p['lightTheme'], 'dark': p['darkThemeName']}, preview=p['preview'])
        result[path] = json.dumps(layout, ensure_ascii=False, indent=2) + '\n'
        result[home / 'themes' / (p['darkThemeName'] + '.json')] = json.dumps(p['darkTheme'], indent=2) + '\n'
        if p.get('lightPalette') is not None:
            result[home / 'themes' / (p['lightTheme'] + '.json')] = json.dumps(p['lightPalette'], indent=2) + '\n'
    keys_path = home / 'keys.json'
    keys = json.loads(keys_path.read_text())
    keys.setdefault('layout:PA-Advanced', copy.deepcopy(keys['layout:PA-Light']))
    result[keys_path] = json.dumps(keys, ensure_ascii=False, indent=2) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, default=ROOT, help='Target app/repository home; defaults to the script directory')
    parser.add_argument('--check', action='store_true', help='Report generated-file drift without writing')
    args = parser.parse_args()
    changes = [(p, text) for p, text in plan(args.home).items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p, _ in changes: print(f'Out of sync: {p.relative_to(args.home.resolve())}')
        if changes: raise SystemExit(1)
        print('Appearance profiles are synchronized.')
        return
    # Everything is validated/planned before writing. Never switch the active
    # layout or overwrite unrelated state; the selected profile remains in place.
    for p, text in changes:
        p.parent.mkdir(parents=True, exist_ok=True)
        temp = p.with_name(p.name + '.appearance-tmp')
        with temp.open('x') as f: f.write(text)
        temp.replace(p)
    print(f'Synchronized {len(changes)} files. Active layout unchanged.')


if __name__ == '__main__':
    main()
