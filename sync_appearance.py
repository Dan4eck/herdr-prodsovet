#!/usr/bin/env python3
"""Compile independent appearance profiles into native themes/layouts and mod helpers."""
import argparse
import copy
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
MODS = ('prodsovet', 'my-files', 'file-tab', 'find', 'session_fork')


def generated(profiles):
    # Herdr does not allow imports between mod directories. These identical files
    # are generated from one config; behavior modules remain shared by layouts.
    return '''// Generated by sync_appearance.py from appearance_profiles.json. Do not edit.
import { shared } from "herdr";
export const allProfiles = ''' + json.dumps(profiles, ensure_ascii=False, indent=2) + ''';
export function profileName() {
  const name = shared("layout");
  return Object.prototype.hasOwnProperty.call(allProfiles, name) ? name : "ProdAdvice";
}
export function appearance(name = profileName()) {
  return allProfiles[name] ?? allProfiles.ProdAdvice;
}
function value(group, key) {
  const result = key.split(".").reduce((node, part) => node?.[part], appearance()[group]);
  if (typeof result !== "number" || !Number.isFinite(result)) throw new Error(`Unknown appearance ${group}: ${key}`);
  return result;
}
export const fontSize = key => value("text", key);
export const metric = key => value("metrics", key);
'''


def validate(config):
    if config.get('version') != 1:
        raise ValueError('Unsupported profile format')
    profiles = config['profiles']
    if set(profiles) != {'ProdAdvice', 'ProdAdvice2'}:
        raise ValueError('Expected independent ProdAdvice and ProdAdvice2 profiles')
    for name, p in profiles.items():
        if not re.fullmatch(r'[A-Za-z0-9 _-]+', name):
            raise ValueError('Unsafe layout name')
        for key in ('ui', 'terminal', 'mono', 'editor'):
            if not isinstance(p['fonts'][key], str) or not p['fonts'][key].strip():
                raise ValueError(f'{name}: missing font {key}')
        if not 8 <= p['fonts']['terminalSize'] <= 72:
            raise ValueError('Invalid terminal font size')
        for section in ('text', 'metrics'):
            for group in p[section].values():
                for n in group.values():
                    if not isinstance(n, (int, float)) or isinstance(n, bool) or not math.isfinite(n) or n <= 0:
                        raise ValueError(f'{name}: invalid {section} value')
        preview = Path(p['preview'])
        if preview.is_absolute() or '..' in preview.parts or preview.parts[0] != 'layouts':
            raise ValueError('Unsafe preview path')
        if not isinstance(p['agentTints'], bool):
            raise ValueError('agentTints must be a boolean')
        colors = [*p['brandColors'].values(), *p['darkTheme']['ansi'], *p['darkTheme'].get('colors', {}).values()]
        colors += [p['darkTheme'][k] for k in ('background', 'foreground', 'selection', 'cursor') if k in p['darkTheme']]
        colors += [c for palette in p['agentPalettes'].values() for c in palette.values()]
        if any(not isinstance(c, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', c) for c in colors):
            raise ValueError(f'{name}: colors must be #rrggbb')
    # Each profile owns a complete schema. Missing values must not fall through
    # to the other profile and accidentally couple their appearances.
    def shape(obj):
        return {k: shape(v) for k, v in obj.items()} if isinstance(obj, dict) else None
    if shape(profiles['ProdAdvice']) != shape(profiles['ProdAdvice2']):
        raise ValueError('Profiles must have the same complete schema')
    return profiles


def plan(home, config_path=None):
    home = Path(home).resolve()
    profiles = validate(json.loads(Path(config_path or ROOT / 'appearance_profiles.json').read_text()))
    result = {}
    helper = generated(profiles)
    for mod in MODS:
        folder = home / 'mods' / mod
        if not folder.is_dir():
            raise ValueError(f'Missing mod directory: {mod}')
        result[folder / 'appearance.js'] = helper
    base = json.loads((home / 'layouts/ProdAdvice.json').read_text())
    for name, p in profiles.items():
        path = home / 'layouts' / (name + '.json')
        layout = json.loads(path.read_text()) if path.exists() else copy.deepcopy(base)
        layout.update(ui_font=p['fonts']['ui'], font=p['fonts']['terminal'], font_size=p['fonts']['terminalSize'],
                      theme={'light': p['lightTheme'], 'dark': name}, preview=p['preview'])
        result[path] = json.dumps(layout, ensure_ascii=False, indent=2) + '\n'
        result[home / 'themes' / (name + '.json')] = json.dumps(p['darkTheme'], indent=2) + '\n'
    keys_path = home / 'keys.json'
    keys = json.loads(keys_path.read_text())
    keys.setdefault('layout:ProdAdvice2', copy.deepcopy(keys['layout:ProdAdvice']))
    result[keys_path] = json.dumps(keys, ensure_ascii=False, indent=2) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, default=ROOT, help='Target app/repository home; defaults to the script directory')
    parser.add_argument('--check', action='store_true', help='Report generated-file drift without writing')
    args = parser.parse_args()
    changes = [(p, text) for p, text in plan(args.home).items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p, _ in changes: print(f'Out of sync: {p.relative_to(args.home.resolve())}')
        if changes: raise SystemExit(1)
        print('Appearance profiles are synchronized.')
        return
    # Everything is validated/planned before writing. Never switch the active
    # layout or overwrite unrelated state; the selected profile remains in place.
    for p, text in changes:
        p.parent.mkdir(parents=True, exist_ok=True)
        temp = p.with_name(p.name + '.appearance-tmp')
        with temp.open('x') as f: f.write(text)
        temp.replace(p)
    print(f'Synchronized {len(changes)} files. Active layout unchanged.')


if __name__ == '__main__':
    main()
